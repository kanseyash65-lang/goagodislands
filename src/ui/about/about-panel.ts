import type { IEventBus } from '../../core/events/event-bus';
import { el } from '../dom';
import { Sheet } from '../sheet';

/** Facts about how the game is built (for judges and the curious). */
const FACTS: readonly [string, string, string][] = [
  ['🎙️', 'Voice-first god game', 'Built for Wispr Flow dictation: speak plain English and the island obeys. Typing and tapping work too.'],
  ['🧠', 'Our own language engine', 'No AI API and no internet. A hand-built pipeline (normalizer → splitter → slot filler → intent resolver) turns sentences like “turn the pirates into chickens” into game actions in under a millisecond.'],
  ['🏝️', 'Everything generated by code', 'Every 3D model, the terrain, the ocean, the music and every sound effect are created at runtime. Zero image, model or audio files.'],
  ['📦', 'One offline file', 'The whole game is a single HTML file under 1 MB. It runs from a USB stick with Wi-Fi off.'],
  ['⚡', 'Fast 3D', 'Three.js instanced rendering with custom shaders: thousands of animated entities at 60 fps in the browser.'],
  ['🧪', 'Tested', 'A deterministic, seeded simulation with 190+ automated tests, strict TypeScript and an offline build check.'],
  ['🌴', 'Made for Goa', 'Goan villages, Portuguese-style houses, chapels, fishing boats, feni, Konkani shouts from the villagers, and a mando-style soundtrack.'],
];

/** "How it's made": the technical story behind the game. */
export class AboutPanel extends Sheet {
  constructor(bus: IEventBus) {
    super(bus, 'about', 'ℹ️ How It’s Made');
  }

  protected render(): void {
    const sec = this.section('Goa God Islands', 'A strategy game where your voice is the only weapon.');
    const list = el('div', 'about-list');
    for (const [icon, title, text] of FACTS) {
      const row = el('div', 'about-row');
      const body = el('div', 'about-body');
      body.append(el('div', 'about-title', title), el('div', 'about-text', text));
      row.append(el('span', 'about-icon', icon), body);
      list.appendChild(row);
    }
    sec.appendChild(list);
  }
}
